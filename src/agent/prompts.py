def with_verification_feedback(message: str, problems: Sequence[tuple[str, str]]) -> str:
    """Сообщение ответа с замечаниями проверки к отклонённому черновику (пары «утверждение, причина»)."""
    lines = [f"— {claim}" + (f": {reason}" if reason else "") for claim, reason in problems]
    return ANSWER_RETRY_TEMPLATE.format(
        message=message, problems="\n".join(lines) or "(без пояснений)", no_answer=NO_ANSWER_PHRASE
    )
